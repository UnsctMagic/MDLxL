const { contextBridge, ipcRenderer, webUtils } = require('electron');
// Electron rejects with "Error invoking remote method '<channel>': Error: <message>"; people see only the message.
const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args).catch(error => {
  const prefix = `Error invoking remote method '${channel}': `, message = String(error?.message || error);
  if (!message.startsWith(prefix)) throw error;
  const text = message.slice(prefix.length);
  throw Error(text.startsWith('Error: ') ? text.slice(7) : text);
});
// A main-process event for the page; ready tells main when the page starts and stops listening.
const subscribe = (channel, callback, { ready } = {}) => {
  const listener = (_, value) => callback(value);
  ipcRenderer.on(channel, listener); if (ready) ipcRenderer.send(ready, true);
  return () => { ipcRenderer.removeListener(channel, listener); if (ready) ipcRenderer.send(ready, false); };
};
// Main sends a request id (alone or as payload.requestId) and waits for one reply carrying it.
const answer = (requestChannel, replyChannel, handler, options) => subscribe(requestChannel, async request => {
  const requestId = request?.requestId ?? request;
  try { ipcRenderer.send(replyChannel, { requestId, ...await handler(request) }); }
  catch (error) { ipcRenderer.send(replyChannel, { requestId, error: String(error?.message || error) }); }
}, options);
