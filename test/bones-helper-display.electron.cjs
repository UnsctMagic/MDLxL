const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { launchApp, closeApp } = require('./helpers/app.cjs');
const { fixturePath } = require('./helpers/fixtures.cjs');
(async () => {
  const out = path.resolve('out/bones-helper-display'); fs.mkdirSync(out, { recursive: true });
  const { app, page, errors } = await launchApp({ out, fixture: fixturePath('footman'), show: 'inactive', pageTimeout: 7000 });
  try {
    await page.locator('[data-hotkey="bones"]').click();
    const quick = page.getByRole('group', { name: 'Quick display', exact: true });
    const bones = quick.locator('input[data-hotkey="display:bones"]');
    const open = async () => { await bones.click({ button: 'right' }); await page.getByRole('menu', { name: 'Bone types', exact: true }).waitFor(); };
    const canvas = page.locator('canvas[data-clean-model-canvas]');
    await canvas.waitFor();
    const both = await canvas.screenshot();
    await open();
    const menu = page.getByRole('menu', { name: 'Bone types', exact: true });
    assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).getAttribute('aria-checked'), 'true');
    assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Bones', exact: true }).getAttribute('aria-checked'), 'true');
    await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).click();
    assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).getAttribute('aria-checked'), 'false');
    await page.keyboard.press('Escape'); await menu.waitFor({ state: 'hidden' });
    assert.ok(!both.equals(await canvas.screenshot()), 'disabling Helpers changes rendered markers');
    for (const editor of ['animation', 'animations', 'bones']) {
      await page.locator(`[data-hotkey="${editor}"]`).click(); await open();
      assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).getAttribute('aria-checked'), 'false', `${editor} shares helper choice`);
      await page.keyboard.press('Escape');
    }
    await bones.setChecked(false); await bones.setChecked(true); await open();
    assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).getAttribute('aria-checked'), 'false', 'master toggle preserves type choices');
    await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).click();
    await menu.getByRole('menuitemcheckbox', { name: 'Bones', exact: true }).click();
    assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Bones', exact: true }).getAttribute('aria-checked'), 'false');
    await page.screenshot({ path: path.join(out, 'bone-types.png') });
    await page.mouse.click(700, 450); await menu.waitFor({ state: 'hidden' });
    const helpersOnly = await canvas.screenshot();
    await open(); await menu.getByRole('menuitemcheckbox', { name: 'Bones', exact: true }).click(); await page.keyboard.press('Escape');
    assert.ok(!helpersOnly.equals(await canvas.screenshot()), 'enabling Bones changes rendered markers independently');
    const before = await canvas.screenshot(), box = await canvas.boundingBox();
    await page.keyboard.down('Alt'); await page.mouse.move(box.x + box.width * .65, box.y + box.height * .5); await page.mouse.down(); await page.mouse.move(box.x + box.width * .65 + 80, box.y + box.height * .5 + 35, { steps: 8 }); await page.mouse.up(); await page.keyboard.up('Alt');
    assert.ok(!before.equals(await canvas.screenshot()), 'normal mouse rotation still changes the camera');
    await page.locator('[data-hotkey="animation"]').click();
    const focused = quick.locator('input[data-hotkey="display:focusedSkeleton"]');
    await bones.setChecked(false); await focused.setChecked(true);
    const picker = page.getByLabel('Movement bone or node');
    const helperId = await picker.locator('optgroup[label="Helpers"] option').first().getAttribute('value');
    await picker.selectOption(helperId);
    await open();
    for (const name of ['Helpers', 'Bones']) if (await menu.getByRole('menuitemcheckbox', { name, exact: true }).getAttribute('aria-checked') === 'false') await menu.getByRole('menuitemcheckbox', { name, exact: true }).click();
    await page.keyboard.press('Escape');
    const focusBox = await canvas.boundingBox(), focusedBefore = await page.screenshot({ clip: focusBox });
    await open();
    for (const name of ['Helpers', 'Bones']) await menu.getByRole('menuitemcheckbox', { name, exact: true }).click();
    await page.keyboard.press('Escape');
    assert.ok(focusedBefore.equals(await page.screenshot({ clip: focusBox })), 'Focused Skeleton ignores both type filters');
    await focused.setChecked(false);
    assert.ok(!focusedBefore.equals(await page.screenshot({ clip: focusBox })), 'Focused Skeleton really rendered the chain');
    await page.getByRole('button', { name: 'POSE', exact: true }).click(); await open();
    assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).count(), 1, 'POSE has the same type menu');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'POSE', exact: true }).click();
    await page.locator('.vis-toggle').click(); await open();
    assert.equal(await menu.getByRole('menuitemcheckbox', { name: 'Helpers', exact: true }).count(), 1, 'VIS has the same type menu');
    await page.keyboard.press('Escape');
    assert.deepEqual(errors, []);
    console.log('bones-helper-display: PASS (menu, independent choices, shared editors, master toggle, rendered type changes, Focused Skeleton exception, POSE, VIS, mouse rotation, Escape, outside dismissal)');
  } finally { await closeApp(app); }
})().catch(error => { console.error(error); process.exitCode = 1; });
