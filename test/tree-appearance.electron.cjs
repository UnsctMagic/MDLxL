const { launchApp, closeApp, settle: settlePage } = require('./helpers/app.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const { BUILT_IN_VIEWPORT_PRESETS: presets } = await import('../src/viewport-appearance.js');
  const root = process.cwd(), out = process.env.MDLXL_SCREENSHOTS || path.join(root, 'out/tree-appearance');
  fs.mkdirSync(out, { recursive: true });
  const profile = path.join(root, 'out/tree-appearance/profile-' + Date.now());
  const file = process.env.MDLXL_TEST_MODEL || 'C:/Users/PC/Desktop/WIP/graveguard_Optimized Weapon (1).mdx';
  const original = fs.readFileSync(file), errors = [];
  const app = (await launchApp({ out: path.resolve('out'), profile: profile, args: ([root, file]).filter(arg => arg !== path.resolve(__dirname, '..') && arg !== '--disable-backgrounding-occluded-windows'), env: { MDLVIS_HEADLESS: '1' } })).app;
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(20000);
    page.on('pageerror', error => errors.push(error.message));
    await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.setSize(1600, 1000); w.setPosition(-3000, 0); w.webContents.setBackgroundThrottling(false); w.showInactive(); });
    await page.getByText('Opened ' + path.basename(file), { exact: true }).waitFor();
    const menu = command => app.evaluate(({ BrowserWindow }, c) => BrowserWindow.getAllWindows()[0].webContents.send('menu', c), command);
    // Appearance shows one page at a time and reopens on the last page used.
    const openPage = name => page.locator('.settings-appearance-nav').getByRole('button', { name, exact: true }).click();
    const settings = async () => { await menu('appearanceSettings'); await page.locator('.settings-appearance-nav').waitFor(); await openPage('Presets'); };
    const done = () => page.getByRole('button', { name: 'Done', exact: true }).click();
    const rgb = hex => 'rgb(' + [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)).join(', ') + ')';
    const style = (locator, key) => locator.evaluate((el, k) => getComputedStyle(el)[k], key);
    await settings();
    const sections = page.locator('.settings-appearance-section');
    assert.equal(await page.locator('.settings-appearance-nav button').count(), 12);
    assert.deepEqual(await sections.locator('h4').allTextContents(), ['Presets'], 'only Presets shows first');
    const folders = sections.filter({ has: page.locator('h4', { hasText: /^Folders & lists$/ }) });
    assert.equal(await folders.count(), 0);
    await openPage('Interface');
    await page.getByLabel('UI accent', { exact: true }).fill('#123456');
    assert.equal(await folders.count(), 0, 'editing another page keeps its own page open');
    await openPage('Lists & folders');
    await page.screenshot({ path: path.join(out, 'appearance-controls.png') });
    await done();
    await menu('Nodes');
    await page.getByLabel('Search nodes').fill('SND');
    await page.locator('.re-tree-row').filter({ hasText: 'SNDxDSPV' }).click();
    await page.getByRole('tree', { name: 'Sound categories' }).waitFor();
    await page.getByLabel('Search sounds').fill('AHAV');
    await page.getByLabel('Search nodes').fill('');
    for (const preset of Object.values(presets)) {
      await settings(); await page.getByLabel('Viewport appearance preset').selectOption(preset.id); await done();
      await page.mouse.move(1, 1);
      const tree = preset.appearance.tree;
      assert.equal(await style(page.locator('.re-node-window .re-list'), 'backgroundColor'), rgb(tree.background), preset.name + ' node background');
      assert.equal(await style(page.locator('.re-sound-tree'), 'backgroundColor'), rgb(tree.background), preset.name + ' folder background');
      assert.equal(await style(page.locator('[data-node-type=Bones] .re-node-icon').first(), 'color'), rgb(tree.nodes.bone), preset.name + ' bone color');
      assert.equal(await style(page.getByRole('button', { name: 'Human', exact: true }), 'color'), rgb(tree.folders.Human), preset.name + ' folder color');
      assert.equal(await style(page.locator('.re-sound-item').first(), 'color'), rgb(tree.text), preset.name + ' sound text');
      if (['mdlvis-vanilla', 'blender-style'].includes(preset.id)) await page.screenshot({ path: path.join(out, preset.name.toLowerCase() + '-folders.png') });
      console.log(preset.name + ': node and sound folder palettes verified');
    }
    await settings();
    await openPage('Lists & folders');
    await page.getByLabel('Tree List background', { exact: true }).fill('#102030');
    await page.getByLabel('Tree List text', { exact: true }).fill('#f0e0d0');
    await page.getByLabel('Node Bones', { exact: true }).fill('#ffaa22');
    await page.getByLabel('Folder Human', { exact: true }).fill('#bbddff');
    await page.getByLabel('List font size', { exact: true }).fill('17'); await page.getByLabel('List font size', { exact: true }).press('Enter');
    await openPage('Presets');
    await page.getByLabel('Custom viewport preset name').fill('My folders');
    await page.getByRole('button', { name: 'Save as custom preset', exact: true }).click();
    const custom = await page.getByLabel('Viewport appearance preset').inputValue();
    await page.getByLabel('Viewport appearance preset').selectOption('mdlvis-vanilla');
    await page.getByLabel('Viewport appearance preset').selectOption(custom);
    await openPage('Lists & folders');
    assert.equal(await page.getByLabel('List font size', { exact: true }).inputValue(), '17');
    await done();
    assert.equal(await style(page.locator('.re-node-window .re-list'), 'backgroundColor'), rgb('#102030'));
    assert.equal(await style(page.locator('.re-sound-item').first(), 'color'), rgb('#f0e0d0'));
    assert.equal(await style(page.locator('.re-node-name').first(), 'fontSize'), '17px');
    assert.equal(await style(page.locator('.re-sound-item').first(), 'fontSize'), '17px');
    assert.equal(await style(page.getByRole('button', { name: 'Human', exact: true }), 'color'), rgb('#bbddff'));
    assert.equal(await style(page.locator('[data-node-type=Bones] .re-node-icon').first(), 'color'), rgb('#ffaa22'));
    await page.screenshot({ path: path.join(out, 'custom-folder-font.png') });
    await page.getByRole('button', { name: 'Close Node Manager', exact: true }).click();
    await menu('Materials');
    assert.equal(await style(page.locator('.re-list'), 'backgroundColor'), rgb('#102030'));
    assert.equal(await style(page.locator('.re-list>button').first(), 'fontSize'), '17px');
    assert.equal(await style(page.locator('.re-list>button:not(.re-selected)').first(), 'color'), rgb('#f0e0d0'));
    assert.equal(await style(page.locator('.re-list>button:not(.re-selected)').first(), 'backgroundColor'), 'rgba(0, 0, 0, 0)');
    await page.waitForFunction(() => !!window.desktop);
    const saved = JSON.parse(fs.readFileSync(path.join(profile, 'settings.json'), 'utf8')).preferences;
    assert.equal(saved.viewportAppearance.tree.fontSize, 17);
    assert.equal(saved.viewportPresets.find(p => p.id === custom).appearance.tree.folders.Human, '#bbddff');
    assert.deepEqual(fs.readFileSync(file), original, 'model bytes unchanged');
    assert.deepEqual(errors, []);
    console.log('PASS categories, all palettes, custom controls, font sizes, preset switching and persisted settings');
  } finally { await closeApp(app).catch(() => {}); }
})().catch(error => { console.error(error); process.exitCode = 1; });
