// Run only through scripts/hidden-run.ps1 / the packaged suite on Windows.
// Uses a local protocol fixture, generated models and a disposable profile.
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { launchApp, closeApp, settle } = require('./helpers/app.cjs');
const out = path.resolve(process.env.MDLXL_AI_TEST_OUT || 'out/ai-questions');
const checks = [];
let errors = [];
const check = (name, passed) => { checks.push({ name, passed: !!passed }); assert.ok(passed, name); };
let app, page, profile, claudeProfile;
(async () => {
  // Seed provider connections before startup; final cleanup removes both profiles.
  profile = path.join(out, 'profile-' + Date.now());
  const ai = path.join(profile, 'ai');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'package.json'), JSON.stringify({ type: 'commonjs' }));
  fs.mkdirSync(ai, { recursive: true }); fs.mkdirSync(path.join(out, 'temp'), { recursive: true });
  fs.mkdirSync(path.join(out, 'bin'), { recursive: true });
  fs.copyFileSync(path.join(__dirname, './fixtures/ai-question-agent.cjs'), path.join(out, 'agent.js'));
  const executable = path.join(out, 'bin/codex.cmd');
  fs.writeFileSync(executable, '@"%dp0%\\..\\agent.js" %*\r\n');
  fs.writeFileSync(path.join(ai, 'connections.json'), JSON.stringify({ provider: 'codex', providers: { codex: { executable, model: 'fixture-model' } } }));
  const { createStarterDocument } = await import('../src/starter-model.js');
  const model = createStarterDocument(), fixture = path.join(out, 'Question.mdx');
  fs.writeFileSync(fixture, model.serialize('mdx'));
  const launched = await launchApp({ fixture, out, env: { MDLVIS_HEADLESS: '', MDLXL_DISABLE_UPDATES: '1', TEMP: path.join(out, 'temp'), TMP: path.join(out, 'temp'), MDLXL_PROFILE: profile } });
  ({ app, page } = launched);
  launched.errors.unshift(...errors); errors = launched.errors;
  await page.waitForSelector('.classic-toolbar', { timeout: 60000 });
  await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.unmaximize(); w.setContentSize(1440, 900); });
  await page.getByRole('button', { name: 'AI assistant', exact: true }).click();
  const prompt = page.getByLabel('AI prompt', { exact: true });
  await prompt.fill('Switch the arms');
  await page.waitForFunction(() => { const button = document.querySelector('.ai-send'); return button && !button.disabled; });
  await prompt.press('Control+Enter');
  const question = page.locator('.ai-question').last();
  await question.getByText('How should I switch the arms?', { exact: true }).waitFor();
  check('question is visible in the model chat', await question.isVisible() && (await question.innerText()).includes('Waiting for your answer'));
  check('no answer is silently preselected', await question.getByRole('radio', { checked: true }).count() === 0 && !await question.getByRole('button', { name: 'Send answer', exact: true }).isEnabled());
  await question.getByRole('radio', { name: /Swap animation/ }).check();
  await question.getByLabel('What should stay unchanged?', { exact: true }).fill('Keep shoulders and enlarged axe');
  await page.screenshot({ path: path.join(out, 'question.png') });
  await question.getByRole('button', { name: 'Send answer', exact: true }).click();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  check('answer reaches native provider and appears in the model chat', (await page.locator('.ai-messages').innerText()).includes('Answer received: Swap animation; Keep shoulders and enlarged axe'));
  await prompt.fill('free-text: clarify the axe'); await prompt.press('Control+Enter');
  await page.locator('.ai-question').last().getByText('Which arm should keep the axe?', { exact: true }).waitFor();
  await page.locator('.ai-question').last().getByLabel('Which arm should keep the axe?', { exact: true }).fill('The right arm');
  await page.locator('.ai-question').last().getByRole('button', { name: 'Send answer', exact: true }).click();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  check('text-only question returns free text to native provider', (await page.locator('.ai-messages').innerText()).includes('Answer received: The right arm'));
  await prompt.fill('Switch the arms again'); await prompt.press('Control+Enter');
  await page.locator('.ai-question').last().getByText('How should I switch the arms?', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Stop', exact: true }).click();
  await page.locator('.ai-question').last().locator('.ai-message-note').filter({ hasText: /Question stopped/ }).waitFor();
  check('Stop removes stale answer controls', await page.locator('.ai-question').last().getByRole('button', { name: 'Send answer', exact: true }).count() === 0);
  async function nextQuestion(text) {
    await page.locator('.ai-send[aria-label="Send"]').waitFor();
    const before = await page.locator('.ai-question').count();
    await prompt.fill(text); await prompt.press('Control+Enter');
    await page.waitForFunction(count => document.querySelectorAll('.ai-question').length > count, before);
    return page.locator('.ai-question').last();
  }
  let extra = await nextQuestion('nonblocking: ask while inspecting');
  await page.getByText('I am inspecting while your question stays open.', { exact: false }).first().waitFor();
  check('nonblocking question stays answerable during subsequent output', await extra.getByLabel('What should stay unchanged?', { exact: true }).isEnabled());
  await extra.getByRole('button', { name: 'Cancel question', exact: true }).click();
  await extra.locator('.ai-message-note').filter({ hasText: /You cancelled/ }).waitFor();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  check('owner can cancel one question directly', await extra.getByRole('button', { name: 'Send answer', exact: true }).count() === 0);
  extra = await nextQuestion('provider-cancel: resolve this question');
  await extra.locator('.ai-message-note').filter({ hasText: /provider cancelled or resolved/ }).waitFor();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  check('provider cancellation removes answer controls but preserves the question text', (await extra.innerText()).includes('How should I switch the arms?') && await extra.getByRole('button', { name: 'Send answer', exact: true }).count() === 0);
  extra = await nextQuestion('turn-ended: finish before the owner answers');
  await extra.locator('.ai-message-note').filter({ hasText: /turn ended before/ }).waitFor();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  check('turn-ended question gives a readable continuation explanation', (await extra.innerText()).includes('Reply in chat to continue.'));
  extra = await nextQuestion('mcp-form: choose model settings');
  await extra.getByLabel('Copy count', { exact: true }).fill('2');
  await extra.getByRole('radio', { name: 'No', exact: true }).check();
  await extra.getByRole('checkbox', { name: 'Shoulders', exact: true }).check();
  await extra.getByRole('checkbox', { name: 'Axe', exact: true }).check();
  await extra.getByRole('button', { name: 'Send answer', exact: true }).click();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  check('MCP form returns typed numbers, booleans and multiple choices', (await page.locator('.ai-messages').innerText()).includes('MCP settings received: {"copies":2,"visible":false,"parts":["Shoulders","Axe"]}'));
  await prompt.fill('protocol-warnings: report provider state'); await prompt.press('Control+Enter');
  await page.getByText('Later activity did not erase the warnings.', { exact: false }).first().waitFor();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  const notices = page.locator('.ai-provider-notice');
  check('provider warnings and model changes remain visible after work completes', (await notices.allTextContents()).some(t => t.includes('Fixture warning remains readable')) && (await notices.allTextContents()).some(t => t.includes('fixture-fallback')));
  const warning = notices.filter({ hasText: 'Fixture connection warning' });
  await warning.locator('summary').click();
  check('warning details open on click', await warning.locator('pre').isVisible());
  await warning.getByRole('button', { name: 'Dismiss provider notice', exact: true }).click();
  check('provider notices can be dismissed', await page.locator('.ai-provider-notice').filter({ hasText: 'Fixture connection warning' }).count() === 0);
  const canvas = page.locator('.classic-view canvas').first(), box = await canvas.boundingBox(), before = await canvas.screenshot();
  await page.keyboard.down('Alt'); await page.mouse.move(box.x + box.width * .45, box.y + box.height * .5); await page.mouse.down();
  await page.mouse.move(box.x + box.width * .65, box.y + box.height * .6, { steps: 16 }); await page.mouse.up(); await page.keyboard.up('Alt');
  await settle(page, 200);
  check('normal mouse drag still rotates the viewport', !before.equals(await canvas.screenshot()));
  check('no renderer errors', errors.length === 0);
  await closeApp(app); app = null;
  claudeProfile = path.join(out, 'claude-profile-' + Date.now());
  fs.mkdirSync(path.join(claudeProfile, 'ai'), { recursive: true });
  fs.copyFileSync(path.join(__dirname, './fixtures/ai-claude-question-agent.cjs'), path.join(out, 'claude-agent.js'));
  const claudeExecutable = path.join(out, 'bin/claude.cmd'); fs.writeFileSync(claudeExecutable, '@"%dp0%\\..\\claude-agent.js" %*\r\n');
  fs.writeFileSync(path.join(claudeProfile, 'ai/connections.json'), JSON.stringify({ provider: 'claude', providers: { claude: { executable: claudeExecutable, model: 'fixture-model' } } }));
  const claude = await launchApp({ fixture, out, env: { MDLVIS_HEADLESS: '', MDLXL_PROFILE: claudeProfile, MDLXL_DISABLE_UPDATES: '1', TEMP: path.join(out, 'temp'), TMP: path.join(out, 'temp') } });
  ({ app, page } = claude);
  claude.errors.unshift(...errors); errors = claude.errors;
  await page.waitForSelector('.classic-toolbar', { timeout: 60000 });
  await page.getByRole('button', { name: 'AI assistant', exact: true }).click();
  await page.getByLabel('AI prompt', { exact: true }).fill('Ask the owner which parts to keep');
  await page.waitForFunction(() => { const button = document.querySelector('.ai-send'); return button && !button.disabled; });
  await page.getByLabel('AI prompt', { exact: true }).press('Control+Enter');
  const claudeQuestion = page.locator('.ai-question').last();
  await claudeQuestion.getByText('Which parts should stay unchanged?', { exact: true }).waitFor();
  await claudeQuestion.getByRole('checkbox', { name: /Shoulders/ }).check(); await claudeQuestion.getByRole('checkbox', { name: /Axe/ }).check();
  await claudeQuestion.getByRole('button', { name: 'Send answer', exact: true }).click();
  await page.locator('.ai-send[aria-label="Send"]').waitFor();
  check('Claude structured questions show and return multiple selections', (await claudeQuestion.innerText()).includes('Shoulders, Axe'));
  check('Claude terminal requests are refused visibly', (await page.locator('.ai-provider-notice').allTextContents()).some(t => t.includes('unavailable tool: Bash')));
  await page.screenshot({ path: path.join(out, 'claude-question.png') });
  check('no renderer errors across both provider paths', errors.length === 0);
})().catch(error => { checks.push({ name: 'exception', passed: false, error: error.stack }); process.exitCode = 1; }).finally(async () => {
  if (process.exitCode && page) { await page.screenshot({ path: path.join(out, 'failure.png') }).catch(() => {}); fs.writeFileSync(path.join(out, 'failure.txt'), await page.locator('body').innerText().catch(() => 'unavailable')); }
  if (app) await closeApp(app);
  for (const seeded of [profile, claudeProfile]) if (seeded) fs.rmSync(seeded, { recursive: true, force: true });
  fs.writeFileSync(path.join(out, 'results.json'), JSON.stringify(checks, null, 2)); console.log(JSON.stringify(checks, null, 2));
});
